// Conditional Statements
const marks = 72;

if (marks >= 80) {
    console.log("Excellent! You got Grade A");
} else if (marks >= 60) {
    console.log("Good job! You got Grade B");
} else if (marks >= 40) {
    console.log("You passed with Grade C");
} else {
    console.log("You need to work harder");
}