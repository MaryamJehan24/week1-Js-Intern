// Ternary Operator
// condition ? value1 : value2

const balance = 1500;

balance >= 1000
    ? console.log("You can buy the product")
    : console.log("You do not have enough money");

// Another example

const number = 7;

number % 2 == 0
    ? console.log("The number is even")
    : console.log("The number is odd");