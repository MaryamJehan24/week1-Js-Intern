// Example 1: Print numbers from 1 to 5
for (let i = 1; i <= 5; i++) {
    console.log(i);
}

// Example 2: Print even numbers from 2 to 10
for (let i = 2; i <= 10; i += 2) {
    console.log(i);
}

// Example 3: Print numbers from 5 to 1
for (let i = 5; i >= 1; i--) {
    console.log(i);
}

// Example 4: Print a name 3 times
for (let i = 1; i <= 3; i++) {
    console.log("Mariam");
}

// Example 5: Print the table of 2
for (let i = 1; i <= 5; i++) {
    console.log("2 x " + i + " = " + (2 * i));
}