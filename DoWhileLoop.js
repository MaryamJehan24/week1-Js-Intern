// Example 1: Print numbers from 1 to 5
let f = 1;
do {
    console.log(f);
    f++;
} while (f <= 5);

// Example 2: Print even numbers from 2 to 10
let g = 2;
do {
    console.log(g);
    g += 2;
} while (g <= 10);

// Example 3: Print numbers from 5 to 1
let h = 5;
do {
    console.log(h);
    h--;
} while (h >= 1);

// Example 4: Print a name 3 times
let j = 1;
do {
    console.log("Mariam");
    j++;
} while (j <= 3);

// Example 5: Print the table of 4
let k = 1;
do {
    console.log("4 x " + k + " = " + (4 * k));
    k++;
} while (k <= 5);