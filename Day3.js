
console.log(" Assignment Operators ");

let a = 10;

console.log("Original value of a:", a);

// Basic assignment
a = 15;
console.log("After = :", a);

// Addition assignment
a += 5;  // a = a + 5
console.log("After += 5:", a);

// Subtraction assignment
a -= 3;  // a = a - 3
console.log("After -= 3:", a);

// Multiplication assignment
a *= 2;  // a = a * 2
console.log("After *= 2:", a);

// Division assignment
a /= 4;  // a = a / 4
console.log("After /= 4:", a);

// Modulus assignment
a %= 4;  // a = a % 4
console.log("After %= 4:", a);

// Exponentiation assignment
a **= 2; // a = a ** 2
console.log("After **= 2:", a);


// 2. Comparison Operators

console.log(" Comparison Operators ");

let x = 10;
let y = 5;
let z = "10";

// Equal to (compares values)
console.log("x == z:", x == z);

// Strict equal to (compares value and type)
console.log("x === z:", x === z);

// Not equal to
console.log("x != y:", x != y);

// Strict not equal to
console.log("x !== z:", x !== z);

// Greater than
console.log("x > y:", x > y);

// Less than
console.log("x < y:", x < y);

// Greater than or equal to
console.log("x >= 10:", x >= 10);

// Less than or equal to
console.log("y <= 5:", y <= 5);
