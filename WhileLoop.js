// Example 1: Print numbers from 1 to 5
let a = 1;
while (a <= 5) {
    console.log(a);
    a++;
}

// Example 2: Print even numbers from 2 to 10
let b = 2;
while (b <= 10) {
    console.log(b);
    b += 2;
}

// Example 3: Print numbers from 5 to 1
let c = 5;
while (c >= 1) {
    console.log(c);
    c--;
}

// Example 4: Print a name 3 times
let d = 1;
while (d <= 3) {
    console.log("Mariam");
    d++;
}

// Example 5: Print the table of 3
let e = 1;
while (e <= 5) {
    console.log("3 x " + e + " = " + (3 * e));
    e++;
}